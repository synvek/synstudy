#!/usr/bin/env bash
# Shared setup for building the `translate` feature (llama.cpp + MNN/PaddleOCR)
# for iOS. Sourced by scripts/package_ios.sh (simulator) and
# scripts/deploy_ios_device.sh (physical device); call `ios_translate_env` AFTER
# parsing --features, BEFORE invoking `dx build`.
#
# 用法:  source scripts/ios_translate_env.sh; ios_translate_env sim|device "$FEATURES"
#
# 为什么需要它
# ------------
# translate feature 会把 llama.cpp（llama-cpp-2 → llama-cpp-sys-2）与
# MNN（rust-paddle-ocr → mnn-sys）从源码用 CMake 编成静态库。dx 默认按 macOS host
# 环境编 CMake，给 iOS 目标产出的是「macOS Mach-O」→ 链接失败。所以要显式注入
# iOS 交叉编译的 CMake toolchain + sysroot / deployment target / arch，以及
# cc-rs / bindgen 使用的 clang flags。
#
# 两个踩过的坑（务必保留对应设置，改动前先看注释）
# ------------------------------------------------
# 1) toolchain 里必须 `set(CMAKE_SYSTEM_PROCESSOR arm64)`：交叉编译时 CMake 不会
#    自行探测该变量（留空），MNN 的 source/backend/cpu/arm/CMakeLists.txt 据此跳过
#    MNNARM64（arm64 NEON 汇编）目标 → 链接期大量
#    "Undefined symbols: _MNNAddC4WithStride…"。
# 2) CFLAGS/CXXFLAGS 必须带 `-Wno-overriding-option`：cc-rs 的
#    flag_if_supported("-std=c++17") 探测要求 stderr 为空；我们注入的 -target 与
#    cc-rs 自动追加的 -mios[-simulator]-version-min 冲突产生的 "overriding option"
#    警告会让探测误判为不支持 → -std=c++17 被丢弃 → llama.cpp wrapper 报
#    "no member named 'filesystem' in namespace 'std'"。
#
# 另外：CMake 不会因为 toolchain 文件内容变化自动重新 configure，旧缓存里的
# CMAKE_SYSTEM_PROCESSOR 等会被直接复用。这里用内容指纹（sha256）检测变更，变更时
# 清掉 mnn-sys / llama-cpp-sys-2 的 native 构建目录与 cargo fingerprint，强制
# build.rs 重跑 cmake configure。真机与模拟器各用自己的 toolchain 文件与指纹，
# 且缓存清理只扫各自的 target/<triple> 目录，避免来回切换时互相清库重编。

ios_translate_env() {
  local KIND="${1:?ios_translate_env 需要 sim|device}"
  local FEATURES="${2:-}"

  # 未启用 translate 时什么都不做。
  case ",$FEATURES," in
    *,translate,*) : ;;
    *) return 0 ;;
  esac

  local SDK_KIND SDK_TRIPLE SCAN_DIRS TOOLCHAIN_FILE STAMP_FILE
  if [ "$KIND" = "device" ]; then
    SDK_KIND="iphoneos"
    SCAN_DIRS="target/aarch64-apple-ios"          # 真机三元组不带 -sim 后缀
  else
    SDK_KIND="iphonesimulator"
    SCAN_DIRS="target/aarch64-apple-ios-sim target/x86_64-apple-ios-sim"
  fi

  local SDK_PATH IOS_MIN
  SDK_PATH="$(xcrun --sdk "$SDK_KIND" --show-sdk-path)"
  IOS_MIN="$(awk -F'"' '/^deployment_target/{print $2}' Dioxus.toml || true)"
  [ -z "${IOS_MIN:-}" ] && IOS_MIN=15.0
  # clang 目标三元组：模拟器带 -simulator 后缀，真机不带。
  if [ "$KIND" = "device" ]; then
    SDK_TRIPLE="arm64-apple-ios${IOS_MIN}"
  else
    SDK_TRIPLE="arm64-apple-ios${IOS_MIN}-simulator"
  fi

  TOOLCHAIN_FILE="$(pwd)/.cargo/ios-cmake-toolchain${KIND:+-$KIND}.cmake"
  STAMP_FILE="${TOOLCHAIN_FILE}.sha256"
  mkdir -p .cargo

  # 每次都重写：内容变化时由下面的指纹检测清缓存、强制重新 configure。
  cat > "$TOOLCHAIN_FILE" <<CMKEOF
# Auto-generated by scripts/ios_translate_env.sh ($KIND build) for the translate feature.
set(CMAKE_SYSTEM_NAME iOS)
set(CMAKE_SYSTEM_PROCESSOR arm64)
set(CMAKE_OSX_SYSROOT "${SDK_PATH}")
set(CMAKE_OSX_DEPLOYMENT_TARGET "${IOS_MIN}")
set(CMAKE_OSX_ARCHITECTURES "arm64")
set(CMAKE_C_COMPILER /usr/bin/clang)
set(CMAKE_CXX_COMPILER /usr/bin/clang++)
set(CMAKE_ASM_COMPILER /usr/bin/clang)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
CMKEOF

  local CUR_HASH
  CUR_HASH="$(shasum -a 256 "$TOOLCHAIN_FILE" | cut -d' ' -f1)"
  if [ ! -f "$STAMP_FILE" ] || [ "$(cat "$STAMP_FILE")" != "$CUR_HASH" ]; then
    # 只扫本次构建对应的 target/<triple> 目录（存在才扫）。
    local EXISTING=() D
    for D in $SCAN_DIRS; do [ -d "$D" ] && EXISTING+=("$D"); done
    if [ ${#EXISTING[@]} -gt 0 ]; then
      find "${EXISTING[@]}" -type d \
        \( -name 'mnn-sys-*' -o -name 'llama-cpp-sys-*' \) \
        \( -path '*/build/*' -o -path '*/.fingerprint/*' \) \
        -prune -exec rm -rf {} + 2>/dev/null || true
    fi
    printf '%s' "$CUR_HASH" > "$STAMP_FILE"
    echo "==> cmake toolchain changed: cleared mnn/llama native build caches ($KIND)"
  fi

  export CMAKE_TOOLCHAIN_FILE="$TOOLCHAIN_FILE"
  export CMAKE_OSX_SYSROOT="$SDK_PATH"
  export CMAKE_OSX_DEPLOYMENT_TARGET="$IOS_MIN"
  export CMAKE_OSX_ARCHITECTURES="arm64"
  # cc-rs 对无版本 iOS target triple 会拿 SDK 版本号当 deployment target，
  # 显式给出以免与下方 CFLAGS/CXXFLAGS 冲突（见坑 #2）。
  export IPHONEOS_DEPLOYMENT_TARGET="$IOS_MIN"
  # bindgen 走 iOS SDK header
  export BINDGEN_EXTRA_CLANG_ARGS="--target=${SDK_TRIPLE} -isysroot ${SDK_PATH}"
  # 强制 Apple clang（避开 PATH 上的 Android NDK clang）
  export CC=/usr/bin/clang
  export CXX=/usr/bin/clang++
  export CFLAGS="-target ${SDK_TRIPLE} -isysroot ${SDK_PATH} -Wno-overriding-option"
  export CXXFLAGS="-target ${SDK_TRIPLE} -isysroot ${SDK_PATH} -fobjc-arc -Wno-overriding-option"
  export SDKROOT="$SDK_PATH"
  export LIBCLANG_PATH="/Applications/Xcode.app/Contents/Developer/Toolchains/XcodeDefault.xctoolchain/usr/lib"
  export CARGO_NET_GIT_FETCH_WITH_CLI=true
  echo "==> translate feature: kind=$KIND toolchain=$TOOLCHAIN_FILE sdk=$SDK_PATH triple=$SDK_TRIPLE min=$IOS_MIN"
}
